/** 설명서 본문 — 카드 여러 개 (넓으면 여러 열, 좁으면 한 열) */
export function guideBody(opts = {}) {
  return h('div.guide',
    h('div.guide-grid', guideSections(opts).map((s) => h('section.guide-card',
      h('h3', s.title),
      s.steps && h('ol', s.steps.map((t) => h('li', t))),
      s.rows && h('dl', s.rows.map(([k, v]) => [h('dt', k), h('dd', v)])),
      s.note && h('p.guide-note', s.note)))),
    h('p.guide-foot', '자세한 설명서 (접속 · 당일 순서 · 문제가 생기면): ',
      h('a', { href: MANUAL_URL, target: '_blank', rel: 'noopener' }, 'docs/manual.md')));
}
